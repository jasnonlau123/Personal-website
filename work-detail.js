let activeIndex = 0;

const image = document.getElementById("viewer-image");
const dots = document.getElementById("viewer-dots");
const title = document.getElementById("project-title");
const subtitle = document.getElementById("project-subtitle");
const narrative = document.getElementById("project-narrative");
const locationText = document.getElementById("project-location");
const yearText = document.getElementById("project-year");
const backLink = document.getElementById("project-back");

document.title = `${work.title} | Liu YongKai`;
title.textContent = work.title;
subtitle.textContent = work.subtitle;
narrative.textContent = work.narrative;
locationText.textContent = work.location;
yearText.textContent = work.year;
backLink.href = fromPage;

function renderDots() {
  dots.innerHTML = galleryImages
    .map(
      (_, index) =>
        `<button class="viewer-dot${index === activeIndex ? " active" : ""}" type="button" aria-label="第 ${index + 1} 张" data-index="${index}"></button>`
    )
    .join("");
  dots.querySelectorAll(".viewer-dot").forEach((button) => {
    button.addEventListener("click", () => {
      showImage(Number(button.dataset.index));
    });
  });
}

function showImage(index) {
  activeIndex = (index + galleryImages.length) % galleryImages.length;
  image.src = galleryImages[activeIndex];
  image.alt = `${work.title} ${activeIndex + 1}`;
  renderDots();
}

document.querySelector(".viewer-arrow-prev").addEventListener("click", () => showImage(activeIndex - 1));
document.querySelector(".viewer-arrow-next").addEventListener("click", () => showImage(activeIndex + 1));

window.addEventListener("keydown", (event) => {
  if (event.key === "ArrowLeft") showImage(activeIndex - 1);
  if (event.key === "ArrowRight") showImage(activeIndex + 1);
});

showImage(0);
